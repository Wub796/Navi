/**
 * The onboarding page for a claim that was consumed by this request.
 * @param {{tenant_id: string, api_key: string, loader_url: string}} input
 * @returns {string}
 */
export function renderBillingSuccessPage({ tenant_id, api_key, loader_url }) {
  const tenant = escapeHtml(tenant_id);
  const key = escapeHtml(api_key);
  const loader = escapeHtml(loader_url);
  // Built as a real tag, then escaped for display, so what a customer copies is
  // exactly what the browser would have parsed.
  const embed = `<script src="${loader}"\n        data-key="${key}"><\/script>`;
  const header = `Authorization: Bearer ${api_key}`;
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex, nofollow, noarchive">
<meta name="referrer" content="no-referrer">
<title>Your Navi key</title>
<style>${STYLE}</style>
</head>
<body>
<main>
  <h1>Your Navi key is ready</h1>
  <p class="lede">Tenant <strong>${tenant}</strong> is provisioned. This page shows the key once.</p>

  <p class="warn">Shown once. This link cannot be opened again — copy the key somewhere safe before you leave.</p>

  <section>
    <h2>Credentials</h2>
    <dl>
      <dt>Tenant</dt>
      <dd><code>${tenant}</code></dd>
      <dt>API key</dt>
      <dd><span class="key"><code>${key}</code></span></dd>
    </dl>
  </section>

  <section>
    <h2>Embed the loader</h2>
    <pre>${escapeHtml(embed)}</pre>
  </section>

  <section>
    <h2>Call the hosted API</h2>
    <pre>${escapeHtml(header)}</pre>
  </section>

  <footer>
    The loader is served from <code>${loader}</code>; if your assets live on another host, substitute that host in the
    snippet. Keep the key server-side and out of source control — it authenticates ingestion for this tenant, and a
    lost key is replaced by rotating the tenant's <code>api_key</code>, not by reopening this page.
  </footer>
</main>
</body>
</html>
`;
}

/**
 * The page for a link that cannot be honoured: missing, expired, already claimed,
 * or requested with the wrong method.
 * @param {{title?: string, detail?: string}} [input]
 * @returns {string}
 */
export function renderBillingClaimErrorPage(input = {}) {
  const title = input.title ?? 'This link has expired';
  const detail = input.detail
    ?? 'A checkout key is shown once, and only inside the fifteen minutes after checkout. This link has either expired or already been used.';
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex, nofollow, noarchive">
<meta name="referrer" content="no-referrer">
<title>${escapeHtml(title)}</title>
<style>${STYLE}</style>
</head>
<body>
<main>
  <h1>${escapeHtml(title)}</h1>
  <p class="lede">${escapeHtml(detail)}</p>
  <section>
    <h2>What to do next</h2>
    <p>Open the success link from your Stripe receipt as soon as checkout completes, or ask the operator of this
      deployment to rotate the tenant's <code>api_key</code> and send you the new value.</p>
  </section>
  <footer>This page never displays a key, and nothing about your session is recorded here.</footer>
</main>
</body>
</html>
`;
}
