/**
 * Derive a sibling endpoint URL from the loader URL when possible.
 * @param {string} loaderUrl
 * @param {string} path
 * @returns {string}
 */
function deriveEndpointUrl(loaderUrl, path) {
  try {
    const parsed = new URL(loaderUrl);
    return `${parsed.origin}${path}`;
  } catch {
    return path;
  }
}

