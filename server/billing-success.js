// The post-checkout onboarding page.
//
// Stripe sends a customer here from the Payment Link's `success_url`
// (`.../v1/billing/success?session_id={CHECKOUT_SESSION_ID}`), and this is the one
// moment the provisioned key is shown: the claim is consumed by rendering it, so a
// refresh or a second visit is a 404 rather than a second disclosure.
//
// Shared by the Cloudflare Worker (`src/worker.ts`) and the self-hosted host
// service (`server/index.js`) rather than written twice, because the security
// headers and the escaping are the part that matters and two copies drift. It lives
// under `server/` because that directory is published in the package, so an install
// from npm can serve the page too; the Worker bundles it like any other module.
//
// The page carries no script. That is not an aesthetic choice: the key is the
// secret, and a page that cannot execute code cannot be made to exfiltrate it. The
// CSP below is the enforcement, and `style-src 'unsafe-inline'` is the only
// exception, for the embedded stylesheet. Interactive integration tabs and 3D vault
// inspection modes use pure CSS `<input type="radio">` state so zero JavaScript
// executes.

/**
 * Headers every response from the onboarding route carries.
 *
 * `default-src 'none'` with no script source means no script can run even if one
 * were injected, `frame-ancestors 'none'` plus `X-Frame-Options` keeps the key out
 * of a frame, `no-referrer` keeps it out of the next site's logs, and `no-store`
 * keeps it out of a shared cache and out of the browser's back-forward cache.
 */
export const BILLING_PAGE_HEADERS = {
  'content-type': 'text/html; charset=utf-8',
  'cache-control': 'no-store',
  'content-security-policy': "default-src 'none'; style-src 'unsafe-inline'; img-src 'self'; base-uri 'none'; form-action 'none'; frame-ancestors 'none'",
  'referrer-policy': 'no-referrer',
  'x-content-type-options': 'nosniff',
  'x-frame-options': 'DENY',
  'cross-origin-opener-policy': 'same-origin',
  'cross-origin-resource-policy': 'same-origin',
  'permissions-policy': 'geolocation=(), camera=(), microphone=()'
};

/**
 * Escape a value for HTML text and attribute context.
 *
 * The key is generated by this repository and the tenant id comes from Stripe
 * metadata, so neither is expected to carry markup — but this page is the one place
 * a customer sees a credential, and "the input is trusted" is the assumption that
 * turns a quoting bug into a key disclosure.
 * @param {string} value
 * @returns {string}
 */
export function escapeHtml(value) {
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

