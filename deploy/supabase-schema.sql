-- Supabase schema for the navi-edge Worker (src/worker.ts).
--
-- Apply with the SQL editor or `psql "$SUPABASE_DB_URL" -f deploy/supabase-schema.sql`.
-- Every statement is idempotent, so re-running it is a no-op rather than an error,
-- and the second block is what upgrades a table created by an earlier release.
--
-- The Worker talks to PostgREST with the service-role key, which bypasses row-level
-- security. Nothing else may read these tables: the anon key is public by definition
-- (it ships in browser code) and a tenant's api_key must never be reachable with it.

create table if not exists public.sites (
  id text primary key,
  api_key text not null,
  allowed_origins text[] not null default array['*']::text[],
  -- NULL is unmetered; 0 is how a revoked subscription is stored, and it refuses.
  max_events_per_window integer,
  window_seconds integer,
  window_start_ms bigint,
  event_count integer not null default 0,
  -- Every lookup filters on this, so an absent column would 500 rather than 401.
  active boolean not null default true,
  updated_at timestamptz not null default now()
);

alter table public.sites add column if not exists api_key text;
alter table public.sites add column if not exists allowed_origins text[] not null default array['*']::text[];
alter table public.sites add column if not exists max_events_per_window integer;
alter table public.sites add column if not exists window_seconds integer;
alter table public.sites add column if not exists window_start_ms bigint;
alter table public.sites add column if not exists event_count integer not null default 0;
alter table public.sites add column if not exists active boolean not null default true;
alter table public.sites add column if not exists updated_at timestamptz not null default now();

alter table public.sites drop constraint if exists sites_max_events_per_window_check;
alter table public.sites add constraint sites_max_events_per_window_check
  check (max_events_per_window is null or max_events_per_window >= 0);
alter table public.sites drop constraint if exists sites_window_seconds_check;
alter table public.sites add constraint sites_window_seconds_check
  check (window_seconds is null or window_seconds > 0);

-- A key lookup expects exactly one row: unique is what makes `sites[0]` the tenant
-- rather than whichever row the planner returned first.
create unique index if not exists idx_sites_api_key on public.sites (api_key);

create table if not exists public.navigation_maps (
  id bigint generated by default as identity primary key,
  site_id text not null references public.sites (id) on delete cascade,
  url text not null,
  payload jsonb not null,
  updated_at timestamptz not null default now()
);

-- The Worker upserts with `on_conflict=site_id,url`, which Postgres resolves
-- against this unique index; without it every update would append a new row.
create unique index if not exists idx_navigation_maps_site_url on public.navigation_maps (site_id, url);

-- Stripe retries a delivery it did not see acknowledged, and a retry must not
-- provision or suspend a site twice. The primary key is the ledger: the Worker
-- inserts with `on_conflict=event_id` and `resolution=ignore-duplicates`, so the
-- second delivery changes no row and is answered `{ ok, duplicate: true }`.
create table if not exists public.webhook_events (
  event_id text primary key,
  received_at timestamptz not null default now()
);

-- One-time post-checkout API-key claims (`GET /v1/billing/session?session_id=cs_...`).
-- Written on `checkout.session.completed` with a 15-minute expiry (`expires_at_ms`)
-- and consumed on the first valid read via `DELETE ...?session_id=eq.<id>&expires_at_ms=gt.<now>`.
create table if not exists public.checkout_claims (
  session_id text primary key,
  tenant_id text not null,
  api_key text not null,
  expires_at_ms bigint not null
);

alter table public.sites enable row level security;
alter table public.navigation_maps enable row level security;
alter table public.webhook_events enable row level security;
alter table public.checkout_claims enable row level security;

-- Default deny: neither public role may touch these tables at all. The Worker is
-- unaffected because the service-role key bypasses RLS.
revoke all on table public.sites from anon, authenticated;
revoke all on table public.navigation_maps from anon, authenticated;
revoke all on table public.webhook_events from anon, authenticated;
revoke all on table public.checkout_claims from anon, authenticated;

-- Granted explicitly rather than inherited from the project's default privileges:
-- a table created from a SQL editor session that has none would otherwise leave the
-- Worker reading and writing with a role that was never given the table.
grant all on table public.sites to service_role;
grant all on table public.navigation_maps to service_role;
grant all on table public.webhook_events to service_role;
grant all on table public.checkout_claims to service_role;
do $$
begin
  -- Guarded because a table that predates the identity column has no sequence.
  if to_regclass('public.navigation_maps_id_seq') is not null then
    execute 'revoke all on sequence public.navigation_maps_id_seq from anon, authenticated';
    execute 'grant usage, select on sequence public.navigation_maps_id_seq to service_role';
  end if;
end $$;

drop policy if exists sites_service_role_all on public.sites;
create policy sites_service_role_all on public.sites
  for all to service_role using (true) with check (true);

drop policy if exists navigation_maps_service_role_all on public.navigation_maps;
create policy navigation_maps_service_role_all on public.navigation_maps
  for all to service_role using (true) with check (true);

drop policy if exists webhook_events_service_role_all on public.webhook_events;
create policy webhook_events_service_role_all on public.webhook_events
  for all to service_role using (true) with check (true);

drop policy if exists checkout_claims_service_role_all on public.checkout_claims;
create policy checkout_claims_service_role_all on public.checkout_claims
  for all to service_role using (true) with check (true);
